import { expect, test } from '@playwright/test'

test('real program, trace replay, register edits and responsive workbench', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.stack ?? error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '一条指令， 看见芯片的思考。' })).toBeVisible()
  await expect(page.getByText('RV32I / SILICON LIFE', { exact: true })).toBeVisible({ timeout: 20000 })
  await page.screenshot({ path: '.local/home.png' })
  await page.getByRole('button', { name: '进入芯片' }).click()
  await expect(page.getByText('Register File', { exact: true })).toBeVisible({ timeout: 20000 })
  await page.screenshot({ path: '.local/workbench.png' })
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12', { timeout: 20000 })
  await expect(page.getByTestId('pc')).toHaveText('0x0000000c')
  await expect(page.getByRole('button', { name: '运行', exact: true })).toBeDisabled({ timeout: 10000 })
  await page.getByRole('button', { name: '回放', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  await page.getByRole('button', { name: '专业模式' }).click()
  await expect(page.getByRole('heading', { name: 'RTL 信号快照' })).toBeVisible()
  await page.getByRole('button', { name: '03 执行 Compute' }).click()
  await page.getByRole('button', { name: '芯生首页', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '.local/preview.png' })
  await page.screenshot({ path: '.local/executed.png', fullPage: true })
  await page.getByRole('button', { name: '复位 CPU' }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('0')
  await page.getByLabel('立即数', { exact: true }).fill('9')
  await expect(page.getByText('0x00900093', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '应用到程序并复位' }).click()
  await page.getByRole('button', { name: '单步指令' }).click()
  await expect(page.getByTestId('register-1').locator('code')).toHaveText('9')
  await page.getByRole('button', { name: '暂停', exact: false }).click()
  await page.getByRole('button', { name: '复位 CPU' }).click()
  await page.getByText('设置初始寄存器', { exact: true }).click()
  await page.getByLabel('寄存器初始值').fill('0xffffffff')
  await page.getByRole('button', { name: '写入初始值' }).click()
  await expect(page.getByTestId('register-1').locator('code')).toHaveText('-1')
  await page.getByRole('button', { name: '恢复视角', exact: false }).click()
  const canvas = page.locator('canvas')
  const bounds = await canvas.boundingBox()
  if (bounds) {
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 80, bounds.y + bounds.height / 2 + 30); await page.mouse.up()
    await page.mouse.wheel(0, 100)
    await page.getByRole('button', { name: '恢复视角', exact: false }).click()
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '.local/mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('chip mesh opens the same scene, with reduced motion and repeated navigation', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.stack ?? error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByText('RV32I / SILICON LIFE', { exact: true })).toBeVisible()
  // Projected center of the chip; its HTML mark passes pointers through to the mesh.
  const canvas = page.locator('canvas')
  const box = await canvas.boundingBox()
  expect(box).not.toBeNull()
  await canvas.click({ position: { x: box!.width / 2, y: box!.height / 2 } })
  await expect(page.getByRole('heading', { name: '让指令，走一遍。' })).toBeVisible()
  await expect(page.getByText('Register File', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  await page.getByRole('button', { name: '探索芯片', exact: true }).click()
  await expect(page.getByText('RV32I / SILICON LIFE', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'CPU 工作台', exact: true }).click()
  await expect(page.getByText('Register File', { exact: true })).toBeVisible()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  expect(errors).toEqual([])
})

test('all three programs execute real arithmetic, memory and branch paths', async ({ page }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '进入芯片' }).click()
  await expect(page.getByText('Data Memory', { exact: true })).toBeVisible({ timeout: 20000 })
  for (const [id, expected, pc] of [['arithmetic', '12', '0x0000000c'], ['memory', '42', '0x00000010'], ['branch', '42', '0x00000014']]) {
    await page.getByLabel('教学程序').selectOption(id)
    await page.getByRole('button', { name: '运行', exact: true }).click()
    await expect(page.getByTestId('register-3').locator('code')).toHaveText(expected, { timeout: 15000 })
    await expect(page.getByTestId('pc')).toHaveText(pc)
    await expect(page.getByRole('button', { name: '运行', exact: true })).toBeDisabled()
    if (id === 'memory') {
      await expect(page.getByTestId('memory-64').locator('code')).toHaveText('42')
      await expect(page.getByTestId('memory-64').locator('small')).toHaveText('2a 00 00 00')
      await page.getByLabel('执行记录').selectOption('2')
      await page.getByRole('button', { name: '04 访存 可跳过' }).click()
      await expect(page.getByTestId('memory-64').locator('code')).toHaveText('42')
      await page.screenshot({ path: '.local/sprint02-memory-a.png', fullPage: true })
    }
    if (id === 'branch') {
      await expect(page.locator('.program-list li').nth(3)).not.toContainText('✓')
      await page.getByLabel('执行记录').selectOption('2')
      await page.getByRole('button', { name: '03 执行 Compute' }).click()
      await expect(page.locator('.phase-description')).toContainText('分支成立')
      await page.screenshot({ path: '.local/sprint02-branch-a.png', fullPage: true })
    }
  }
  expect(errors).toEqual([])
})

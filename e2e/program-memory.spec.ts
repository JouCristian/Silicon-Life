test('ROM file preview requires confirmation; bad imports preserve program; exports round-trip', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await openLab(page)
  const panel = await rom(page, 'v2.0 raw\n00500093 00700113 002081b3')
  await expect(page.getByTestId('rom-preview')).toContainText('3 单元')
  await expect(page.getByLabel('教学程序')).toHaveValue('arithmetic')
  await page.getByRole('button', { name: '确认导入 ROM' }).click()
  await expect(page.getByLabel('教学程序')).toHaveValue('custom')
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  await rom(page, '00500093 ffffffff')
  await expect(panel.getByRole('alert')).toContainText('第 2 条 [0xffffffff]')
  await expect(page.getByRole('button', { name: '确认导入 ROM' })).toBeDisabled()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  await expect(page.locator('.program-list li')).toHaveCount(3)
  for (const text of ['v3.0 hex words plain\n00', 'v2.0 raw\n9999999999*00500093']) {
    await rom(page, text); await expect(panel.getByRole('alert')).toBeVisible()
    await expect(page.getByRole('button', { name: '确认导入 ROM' })).toBeDisabled()
  }
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 ROM', exact: true }).click()
  const downloaded = await downloading, path = await downloaded.path()
  expect(path).toBeTruthy()
  await page.getByLabel('ROM HEX 文件').setInputFiles(path!)
  await expect(page.getByTestId('rom-preview')).toContainText('3 单元')
  await page.getByRole('button', { name: '确认导入 ROM' }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('12')
  expect(errors).toEqual([])
})

test('manual initial RAM drives LW and SW; reset restores configuration', async ({ page }) => {
  await openLab(page)
  await page.getByText('编辑初始 RAM', { exact: true }).click()
  await page.getByRole('button', { name: '写入初始 RAM', exact: true }).click()
  await expect(page.getByTestId('memory-64').locator('code')).toHaveText('42')
  await rom(page, '04002183\n00302023') // LW x3,64(x0); SW x3,0(x0)
  await page.getByRole('button', { name: '确认导入 ROM' }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('42')
  await page.getByLabel('内存起始地址').fill('0')
  await expect(page.getByTestId('memory-0').locator('code')).toHaveText('42')
  await expect(page.getByTestId('memory-0')).toHaveClass(/changed/)
  await expect(page.getByRole('button', { name: '写入初始 RAM', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '复位 CPU' }).click()
  await expect(page.getByTestId('memory-0').locator('code')).toHaveText('0')
  await page.getByLabel('内存起始地址').fill('64')
  await expect(page.getByTestId('memory-64').locator('code')).toHaveText('42')
  await page.getByLabel('RAM 编辑地址').fill('65')
  await page.getByRole('button', { name: '写入初始 RAM', exact: true }).click()
  await expect(page.locator('.memory-edit').getByRole('alert')).toContainText('对齐')
})

test('RAM HEX 32/8-bit import, offsets, overflow rejection and LW agree', async ({ page }) => {
  await openLab(page)
  await page.locator('.memory-panel .hex-panel summary').click()
  await page.getByLabel('RAM HEX 文件').setInputFiles({ name: 'memory-init.hex', mimeType: 'text/plain', buffer: Buffer.from('v2.0 raw\n16*00000000 0000002a') })
  await expect(page.getByTestId('ram-preview')).toContainText('17 单元')
  await page.getByRole('button', { name: '确认导入 RAM' }).click()
  await expect(page.getByTestId('memory-64').locator('small')).toHaveText('2a 00 00 00')
  await rom(page, '04002183')
  await page.getByRole('button', { name: '确认导入 ROM' }).click()
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('42')
  await page.getByRole('button', { name: '复位 CPU' }).click()
  await page.getByLabel('RAM 数据宽度').selectOption('8')
  await page.getByLabel('RAM 装载地址').fill('1023')
  await page.getByLabel('RAM HEX 文件').setInputFiles({ name: 'bytes.hex', mimeType: 'text/plain', buffer: Buffer.from('2a 00 00 00') })
  await expect(page.locator('.memory-panel .hex-panel').getByRole('alert')).toContainText('边界')
  await expect(page.getByRole('button', { name: '确认导入 RAM' })).toBeDisabled()
  await expect(page.getByTestId('memory-64').locator('code')).toHaveText('42')
  await page.getByLabel('RAM 装载地址').fill('64')
  await page.getByRole('button', { name: '确认导入 RAM' }).click()
  await page.getByLabel('教学程序').selectOption('branch')
  await page.getByLabel('教学程序').selectOption('custom')
  await page.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.getByTestId('register-3').locator('code')).toHaveText('42')
  await page.screenshot({ path: '.local/sprint03-ram.png' })
})

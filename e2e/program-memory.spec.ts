import { expect, test, type Page } from '@playwright/test'

async function openLab(page: Page) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: '进入芯片' }).click()
  await expect(page.getByText('Register File', { exact: true })).toBeVisible()
  await page.getByLabel('传播速率').selectOption('2')
}
async function rom(page: Page, text: string) {
  const panel = page.locator('.program-panel .hex-panel')
  if (!await panel.evaluate(el => el.hasAttribute('open'))) await panel.locator('summary').click()
  await page.getByLabel('ROM HEX 文件').setInputFiles({ name: 'program.hex', mimeType: 'text/plain', buffer: Buffer.from(text) })
  return panel
}

